CREATE DATABASE IndianUsedCarDb;
GO

USE IndianUsedCarDb;
GO

CREATE TABLE Cars (
    CarId INT IDENTITY(1,1) PRIMARY KEY,
    Brand NVARCHAR(50) NOT NULL,
    Model NVARCHAR(50) NOT NULL,
    Variant NVARCHAR(50) NULL,
    Year INT NOT NULL,
    Price DECIMAL(12,2) NOT NULL,
    Mileage INT NOT NULL,
    FuelType NVARCHAR(20) NOT NULL,
    Transmission NVARCHAR(20) NOT NULL,
    RegistrationNumber NVARCHAR(20) UNIQUE NOT NULL,
    ImageUrl NVARCHAR(500) NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'Available',
    IsDeleted BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);
GO

CREATE TABLE Customers (
    CustomerId INT IDENTITY(1,1) PRIMARY KEY,
    FullName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(100) NOT NULL,
    Phone NVARCHAR(15) NOT NULL,
    City NVARCHAR(50) NOT NULL,
    State NVARCHAR(50) NOT NULL,
    IsDeleted BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);
GO

CREATE TABLE Bills (
    BillId INT IDENTITY(1,1) PRIMARY KEY,
    InvoiceNumber NVARCHAR(50) UNIQUE NOT NULL,
    CarId INT NOT NULL FOREIGN KEY REFERENCES Cars(CarId),
    CustomerId INT NOT NULL FOREIGN KEY REFERENCES Customers(CustomerId),
    SalePrice DECIMAL(12,2) NOT NULL,
    CgstAmount DECIMAL(12,2) NOT NULL,
    SgstAmount DECIMAL(12,2) NOT NULL,
    TotalAmount DECIMAL(12,2) NOT NULL,
    PaymentMethod NVARCHAR(30) NOT NULL,
    SaleDate DATETIME2 NOT NULL DEFAULT GETUTCDATE(),
    IsDeleted BIT NOT NULL DEFAULT 0
);
GO
